"""Management's own liquidity statement, quoted from the periodic filing the metrics stage already holds.

Defect (offline-review/DEFECT_LIQUIDITY_UNSUPPORTED_20261113.md): the liquidity need could be met only by a
going-concern conclusion, so for healthy issuers the answer said a filing "was read and no passage met this
version's selection rules" although the filing states management's liquidity position (CNK, TRIP, COHU, LXRX,
CRDO, VIRC ...). Excerpts are retained filing text from pilot Runs 8, 9 and 11; other inputs are constructed and
labelled.
"""
