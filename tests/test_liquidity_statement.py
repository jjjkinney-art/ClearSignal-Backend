def test_the_flag_defaults_off(monkeypatch):
    assert type(settings).model_fields['liquidity_statements_enabled'].default is False
    monkeypatch.setattr(settings, 'liquidity_statements_enabled', False, raising=False)
    assert L.enabled() is False
    monkeypatch.setattr(settings, 'liquidity_statements_enabled', True, raising=False)
    assert L.enabled() is True


def test_threshold_questions_never_get_a_liquidity_statement(monkeypatch):
    from app.services import filing_metric_evidence as F
    thesis = 'What is the investment thesis for Cinemark Holdings, Inc., what supports it, and what could invalidate it? Distinguish reported facts from inference and cite material claims.'
    threshold = 'Which valuation and operating assumptions would make Cinemark Holdings, Inc. attractive or unattractive? Explain decision thresholds, evidence and uncertainty without inventing figures.'
    monkeypatch.setattr(settings, 'liquidity_statements_enabled', True, raising=False)
    assert F._liquidity_wanted('CNK', thesis) is True
    assert F._liquidity_wanted('CNK', threshold) is False
    monkeypatch.setattr(settings, 'liquidity_statements_enabled', False, raising=False)
    assert F._liquidity_wanted('CNK', thesis) is False
