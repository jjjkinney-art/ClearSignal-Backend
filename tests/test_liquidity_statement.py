# --- binding ---------------------------------------------------------------------------------------------------

def bound_item(key='CNK'):
    item = extract(key)[0]
    item.availability_status, item.freshness_status = 'available', 'current'
    return item


def test_the_stored_binding_is_rechecked():
    item = bound_item()
    assert L.bound_liquidity_statement(item, ticker='CNK', cik=row_cik('CNK'))['claim_kind'] == 'issuer_liquidity_statement'
    assert L.bound_liquidity_statement(item, ticker='CNKX', cik=row_cik('CNK')) is None
    assert L.bound_liquidity_statement(item, ticker='CNK', cik='0000000001') is None
    for field, bad in (('quote', 'altered'), ('statement', 'We believe nothing.'), ('statement_offset', 3)):
        tampered = bound_item()
        tampered.liquidity_statements[0][field] = bad
        assert L.bound_liquidity_statement(tampered, ticker='CNK', cik=row_cik('CNK')) is None
    stale = bound_item()
    stale.freshness_status = 'stale'
    assert L.bound_liquidity_statement(stale, ticker='CNK', cik=row_cik('CNK')) is None
    edited = bound_item()
    edited.summary += ' Strong liquidity.'
    assert L.bound_liquidity_statement(edited, ticker='CNK', cik=row_cik('CNK')) is None


